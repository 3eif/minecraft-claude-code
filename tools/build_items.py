"""Writes hooks/items.ts: the items the desktop app draws beside tool calls, as SVG path
fragments (one path per colour, one rectangle per run of a row), from assets/item.

  uv run --no-project --with pillow python tools/build_items.py
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ITEMS = ['iron_pickaxe', 'filled_map', 'writable_book', 'spyglass', 'compass', 'armor_stand', 'paper', 'ender_eye']

def frag(im):
    by = {}
    px = im.load()
    for y in range(im.height):
        x = 0
        while x < im.width:
            c = px[x, y]
            if c[3] == 0:
                x += 1
                continue
            x0 = x
            while x < im.width and px[x, y] == c:
                x += 1
            by.setdefault(c, []).append(f'M{x0} {y}h{x - x0}v1h-{x - x0}z')
    out = ''
    for (r, g, b, a), runs in by.items():
        op = '' if a == 255 else f' fill-opacity="{a / 255:.2f}"'
        out += f'<path fill="#{r:02x}{g:02x}{b:02x}"{op} d="{"".join(runs)}"/>'
    return out

items = {name: frag(Image.open(os.path.join(ROOT, 'assets/item', name + '.png')).convert('RGBA')) for name in ITEMS}
with open(os.path.join(ROOT, 'hooks/items.ts'), 'w') as f:
    f.write('// Generated by tools/build_items.py from assets/item: 16 by 16 item pictures as SVG path fragments.\n\n'
            f'export const ITEMS: Record<string, string> = {json.dumps(items, indent=1)}\n')
print({k: len(v) for k, v in items.items()})
